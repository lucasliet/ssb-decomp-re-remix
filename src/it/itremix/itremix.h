#ifndef _ITREMIX_H_
#define _ITREMIX_H_

/*
 * Smash Remix custom items (PORT only).
 *
 * Remix adds items with ids from 0x2D (Item.asm add_item). Each one fills a
 * row of Remix's extended tables: spawn routine, spawn gfx flag, pre-pickup
 * (hold), pickup (consume), drop, throw and player collision (touch). The
 * vanilla code indexes its own tables by item kind; Item.asm patches those
 * lookups to use the extended tables for ids >= 0x2D. The port does the same
 * through itRemixGetItemDesc at the same vanilla sites.
 *
 * Each item is ported in decomp/src/it/itremix/<item>.c and exports one
 * `const ITRemixItemDesc dITRemix<Name>ItemDesc`. itremixitems.c lists them
 * (generated by tools/gen_remix_items.py).
 */

#include <it/item.h>
#include <ft/fighter.h>

#define ITREMIX_KIND_START 0x2D /* Item.asm add_item: item_id = current_item + 0x2D */

typedef struct ITRemixItemDesc
{
    s32 kind;                                                       /* Remix item id (Item.<Name>.id) */
    GObj* (*proc_make)(GObj *parent_gobj, Vec3f *pos, Vec3f *vel, u32 flags); /* SPAWN_ITEM */
    sb32 is_show_spawn_gfx;                                         /* SHOW_GFX_WHEN_SPAWNED */
    void (*proc_hold)(GObj *item_gobj);                             /* PICKUP_ITEM_INIT (pre-pickup table) */
    void (*proc_consume)(FTStruct *fp, GObj *item_gobj);            /* PICKUP_ITEM_MAIN (consume-type pickup), may be NULL */
    void (*proc_dropped)(GObj *item_gobj);                          /* DROP_ITEM, may be NULL */
    void (*proc_thrown)(GObj *item_gobj);                           /* THROW_ITEM, may be NULL */
    void (*proc_touch)(FTStruct *fp, ITStruct *ip, GObj *item_gobj); /* PLAYER_COLLISION (touch-type), may be NULL */
} ITRemixItemDesc;

extern const ITRemixItemDesc *const dITRemixItemDescs[];
extern const s32 dITRemixItemDescsNum;

/** TRUE when `kind` is a Remix custom item id. */
sb32 itRemixIsCustomKind(s32 kind);

/** Descriptor of Remix item `kind`, or NULL when it has no port (logged once per kind). */
const ITRemixItemDesc* itRemixGetItemDesc(s32 kind);

/**
 * Tail of ftCommonLightGetProcDamage at 0x80145C4C, where the PICKUP_ITEM_MAIN
 * of most Remix items jumps: destroys the item and counts the 1P tomato bonus.
 */
void itRemixConsumeTomatoTail(FTStruct *fp, GObj *item_gobj);

/** Item.asm extend_item_spawn_: spawns Remix item `kind`; NULL when it has no port. */
GObj* itRemixMakeItem(GObj *parent_gobj, s32 kind, Vec3f *pos, Vec3f *vel, u32 flags);

#endif
